namespace Markout;

/// <summary>
/// Non-generic interface for runtime enumeration of registered types.
/// </summary>
public interface IMarkoutTypeInfo
{
    /// <summary>
    /// Gets the type this info represents.
    /// </summary>
    Type Type { get; }

    /// <summary>
    /// Gets the template binding name for this type (snake_case).
    /// Used by <c>Markout.Templates.MarkoutTemplate.BindContext</c> for automatic registration.
    /// </summary>
    string BindingName { get; }

    /// <summary>
    /// Serializes a value to the given orchestrator.
    /// </summary>
    /// <param name="orchestrator">The orchestrator to serialize to.</param>
    /// <param name="value">The value to serialize (must be of the correct type).</param>
    void Serialize(MarkoutWriter orchestrator, object value);
}

/// <summary>
/// Contains metadata and serialization logic for a specific type.
/// Generated by the source generator for each [MarkoutSerializable] type.
/// </summary>
/// <typeparam name="T">The type this info represents.</typeparam>
public abstract class MarkoutTypeInfo<T> : IMarkoutTypeInfo
{
    /// <summary>
    /// Gets the type this info represents.
    /// </summary>
    public Type Type => typeof(T);

    /// <summary>
    /// Gets the template binding name for this type (snake_case).
    /// Generated from the type name: CveReport → cve_report.
    /// </summary>
    public abstract string BindingName { get; }

    /// <summary>
    /// Serializes a value to the given orchestrator.
    /// </summary>
    /// <param name="orchestrator">The orchestrator to serialize to.</param>
    /// <param name="value">The value to serialize.</param>
    public abstract void Serialize(MarkoutWriter orchestrator, T value);

    /// <summary>
    /// Serializes a value to the given orchestrator (non-generic implementation).
    /// </summary>
    void IMarkoutTypeInfo.Serialize(MarkoutWriter orchestrator, object value)
    {
        Serialize(orchestrator, (T)value);
    }
}
